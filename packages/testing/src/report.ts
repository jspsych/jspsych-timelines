import * as fs from "fs";
import * as path from "path";

import type { Fixture } from "./fixture";
import { untypedValues } from "./fixture";
import type { ReproductionResults } from "./reproduction";
import { GAP_CLASSES } from "./types";

export interface ReportInput {
  task: string;
  fixture: Fixture;
  results: ReproductionResults;
  reportPath: string;
  /** hand-written commentary, appended as it is */
  notes?: string;
}

const KIND_TEXT: Record<string, string> = {
  behaviour:
    "Counts per phase and block, exact condition counts, rows present or absent, timeouts under forced slow RTs, keys, device, mapping across seeds",
  "recorded-parameter":
    "A duration, interval or spacing equals the value in the data row and in the plugin parameter. Both come from one variable and the data-only simulator ignores time, so this proves the value arrived, not that the browser times it.",
  structure:
    "The rendered HTML or built timeline contains it: colours, sizes, positions, instruction sentences, plugins and their parameters",
};

const cell = (v: unknown) =>
  String(typeof v === "string" ? v : JSON.stringify(v))
    .replace(/\|/g, "\\|")
    .replace(/\n/g, " ");

const pct = (a: number, b: number) => (b ? `${((100 * a) / b).toFixed(1)}%` : "n/a");

/** Render `reproduction.md` from the results of a run. */
export function renderReproductionMd(input: ReportInput): string {
  const { task, fixture, results: res } = input;
  const t = res.tallies;
  const out: string[] = [];
  const p = (...lines: string[]) => out.push(...lines);

  const optionNames = new Set(fixture.options.map((o) => o.name));
  const untyped = untypedValues(fixture);
  const typedNull = fixture.options
    .flatMap((o) => o.components.flatMap((c) => c.observed))
    .filter((x) => x.ok && x.value === null).length;
  const additions = res.level1.filter((x) => x.labelledAddition);
  const additionRows = additions.reduce((a, x) => a + x.sources.length, 0);
  const checked = res.level1.filter((x) => x.status === "checked");
  const checkedRows = checked.reduce((a, x) => a + x.sources.length, 0);
  const gapped = res.level1.filter((x) => x.status === "not expressible");
  const gappedRows = gapped.reduce((a, x) => a + x.sources.length, 0);

  p(
    `# Reproduction of the literature values`,
    ``,
    `How much of what the ${task} literature varied can this package express, and does each setting show up in the data? The source is the generated spec (${fixture.spec}). The fixture is \`reproduction/spec-observed.json\`, generated by \`@jspsych-timelines/testing\` (\`scripts/fixture-from-spec.mjs\`); the retyping table is \`reproduction/adapter.ts\`; the checks are the shared checks of \`@jspsych-timelines/testing\` plus \`reproduction/checks.ts\`, run by \`src/reproduction.spec.ts\`. The tallies below come from \`reproduction/results.json\` and are asserted against \`reproduction/expected-tallies.json\` on every test run. \`UPDATE_REPRODUCTION=1 npx jest\` regenerates both and this file.`,
    ``,
    `This file is generated. Commentary that belongs to the package goes in \`reproduction/notes.md\`, which is appended at the end.`,
    ``,
    `## Numbers`,
    ``,
    `**Observed values.** The spec lists ${t.observed_values_total} observed values over the ${optionNames.size} options; ${t.typed_values_total} are typed, ${untyped.length} are not.`,
    ``,
    `| | Rows | Distinct (option, component, value) |`,
    `|---|---|---|`,
    `| Observed values | ${t.observed_values_total} | |`,
    `| Untyped by the spec, not attempted | ${untyped.length} | |`,
    `| Typed with value \`null\` (absent), skipped | ${typedNull - additionRows} | |`,
    `| Typed with value \`null\` that mean "until response" or "untimed", **added** as labelled additions | ${additionRows} | ${additions.length} |`,
    `| Cases in level 1 | ${checkedRows + gappedRows} | ${t.level1_distinct_cases} |`,
    `| Expressible and checked | ${checkedRows} (${pct(checkedRows, checkedRows + gappedRows)}) | ${
      t.level1_checked
    } (${pct(t.level1_checked, t.level1_distinct_cases)}) |`,
    `| Not expressible | ${gappedRows} | ${t.level1_not_expressible} |`,
    ``,
    `Of all ${t.observed_values_total} rows, ${checkedRows} (${pct(
      checkedRows,
      t.observed_values_total
    )}) are expressible and checked. The ${
      t.level1_checked
    } checked cases split by what the check can see:`,
    ``,
    `| Check kind | Cases | What it asserts |`,
    `|---|---|---|`
  );
  for (const kind of ["behaviour", "recorded-parameter", "structure"]) {
    const n = checked.filter((x) => x.kind === kind).length;
    p(`| ${kind[0].toUpperCase()}${kind.slice(1).replace("-", " ")} | ${n} | ${KIND_TEXT[kind]} |`);
  }

  const l2 = res.level2;
  const fully = l2.filter((x) => x.gaps.length === 0);
  const totalConfigs = fixture.study_configurations.length;
  p(
    ``,
    `## Study configurations`,
    ``,
    `${totalConfigs} configurations, ${l2.length} fully typed. Level 2 builds each fully typed one with all its options at once, simulates it, checks the resolved options against the values it reports, and runs the check of every option it names.`,
    ``,
    `| | Configurations |`,
    `|---|---|`,
    `| Fully typed (spec flag) | ${l2.length} of ${totalConfigs} |`,
    `| Fully expressible and all values checked | ${fully.length} of ${l2.length} (${pct(
      fully.length,
      l2.length
    )}) |`,
    `| Expressible except some values | ${l2.length - fully.length} |`,
    ``,
    `| Source | Citation | Keys | Expressible | Tied to reported value | Not expressible | Assumed, not reported |`,
    `|---|---|---|---|---|---|---|`
  );
  for (const x of l2) {
    p(
      `| ${x.source} | ${cell(x.citation)} | ${x.n_keys} | ${x.keys_expressible} | ${
        x.tied_to_reported_value
      } | ${x.gaps.length ? x.gaps.map((g) => `\`${g.key}\``).join(", ") : ""} | ${
        x.assumed.length ? x.assumed.map((a) => `\`${a}\``).join(", ") : ""
      } |`
    );
  }
  p(
    ``,
    `Companion settings that a configuration needed but did not state count as expressible and are listed under "Assumed", because they are assumptions.`,
    ``,
    `## Gaps`,
    ``,
    `Classes: ${GAP_CLASSES.join(", ")}.`,
    ``,
    `### Typed values the package cannot express (${gapped.length} cases)`,
    ``
  );
  if (gapped.length) {
    p(`| Option / value | Sources | Class | Why |`, `|---|---|---|---|`);
    for (const g of gapped)
      p(
        `| \`${g.option}: ${cell(g.value)}\` | ${g.sources.join(", ")} | ${g.gap} | ${cell(
          g.reason
        )} |`
      );
    p(``);
    const byClass = GAP_CLASSES.map(
      (c) => [c, gapped.filter((g) => g.gap === c).length] as const
    ).filter(([, n]) => n);
    p(`By class: ${byClass.map(([c, n]) => `${c} ${n}`).join(", ")}.`, ``);
  } else p(`None.`, ``);

  p(`### Untyped values (${untyped.length} rows, not attempted)`, ``);
  if (untyped.length) {
    p(`| Option / raw value | Source | Spec's note |`, `|---|---|---|`);
    for (const u of untyped)
      p(`| \`${u.option}\`: ${cell(u.raw)} | ${u.source} | ${cell(u.note ?? "")} |`);
    p(``);
  } else p(`None.`, ``);

  if (input.notes) p(input.notes.trim(), ``);
  return out.join("\n");
}

export function writeReproductionMd(input: ReportInput) {
  fs.mkdirSync(path.dirname(input.reportPath), { recursive: true });
  fs.writeFileSync(input.reportPath, renderReproductionMd(input));
}
